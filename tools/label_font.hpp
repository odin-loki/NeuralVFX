inline const Glyph* glyph(char c) {
  const char u = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
  for (const Glyph& g : kFont)
    if (g.c == u) return &g;
  return nullptr;  // a space, or a sign the font lacks: blank
}

// Draws `text` with its top-left corner at (x, y), each font pixel `scale` x `scale` screen pixels, 6 * scale apart;
// put(px, py) sets one screen pixel (the caller clips).
template <class Put>
void draw_text(std::string_view text, int x, int y, int scale, Put&& put) {
  for (const char c : text) {
    if (const Glyph* g = glyph(c)) {
      for (int r = 0; r < 7; ++r)
        for (int col = 0; col < 5; ++col)
          if (g->rows[static_cast<std::size_t>(r)][static_cast<std::size_t>(col)] == '#')
            for (int dy = 0; dy < scale; ++dy)
              for (int dx = 0; dx < scale; ++dx) put(x + col * scale + dx, y + r * scale + dy);
    }
    x += 6 * scale;
  }
}

inline int text_width(std::string_view text, int scale) { return static_cast<int>(text.size()) * 6 * scale - scale; }

